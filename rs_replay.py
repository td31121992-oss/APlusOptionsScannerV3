"""Shadow replay and nightly review of the relative-strength leaderboard (RESEARCH ONLY: reads recorded ticks and the paper journal, changes nothing).

Three questions, kept apart on purpose:

  1. DETECTION LATENCY   how quickly is a leader / laggard flagged?   (lag_s, compute_ms, since_rs1_s in the live event log, see rs_leaders.py)
  2. DECISION QUALITY    once flagged, what does the stock do next, against the market?   (forward move 5 / 15 / 30 minutes later, minus the median stock's move over the same minutes)
  3. LEDGER REPLAY       what did the board say about each paper trade at the minute we entered, and how did those trades end?

The recorded ticks (data/ticks/<day>/*.csv.gz, read with tick_gz so a crashed day still loads) are fed through the same RSTracker the live recorder uses, in time order, at 5-second resolution
(each stock keeps its last tick per 5 seconds; the exchange VWAP is rebuilt as sum(price x traded qty) / sum(traded qty)). With a live event log for the day (data/rs_events/<day>.csv) the
review uses it (real latency); otherwise it uses the events regenerated by the replay (latency is then at 5-second resolution and has no wall-clock part).

    data/rs_review/<day>.json     events with forward moves, the grouped quality table, the latency summary and the ledger join for that day
    data/rs_review/summary.md     the same, one section per reviewed day, newest first

    python rs_replay.py [YYYY-MM-DD ...] [--replay]       default: today; --replay ignores the live event log and uses the regenerated events
"""

from __future__ import annotations

import csv
import heapq
import json
import statistics as st
import sys
import time
from datetime import date, datetime
from pathlib import Path
from typing import Any, Iterable, Mapping

import rs_leaders
import tick_gz

ROOT = Path(__file__).resolve().parent
STEP_S = 5.0
HORIZONS_MIN = (5, 15, 30)
MARKET_END_S = 15 * 3600 + 30 * 60


def _secs(ts: str) -> float:
    h, m, s = ts.split(":")
    return int(h) * 3600 + int(m) * 60 + float(s)


def _f(v: str) -> float:
    try:
        return float(v)
    except ValueError:
        return 0.0


def load_samples(root: Path, day: str, step: float = STEP_S) -> list[tuple[float, str, float, float, float, float, float]]:
    """All stocks' ticks merged in time order and thinned to one per stock per `step` seconds: (t, symbol, ltp, cumulative volume, vwap, bid, ask)."""
    streams = [_index_stream(root, day)]
    for path in sorted((root / "data" / "ticks" / day).glob("*.csv.gz")):
        text, _members, _bad = tick_gz.read_text(path)
        lines = text.splitlines()
        if len(lines) < 2:
            continue
        col = {name: i for i, name in enumerate(lines[0].split(","))}
        try:
            i_ts, i_sym, i_ltp, i_vol, i_bid, i_ask, i_tq = (col[k] for k in ("ts", "sym", "ltp", "vol", "bid", "ask", "tq"))
        except KeyError:
            continue
        out, pv, pq, bucket, last = [], 0.0, 0.0, None, None
        for ln in lines[1:]:
            p = ln.split(",")
            if len(p) <= max(i_tq, i_ask):
                continue
            try:
                t, ltp = _secs(p[i_ts]), float(p[i_ltp])
            except ValueError:
                continue
            tq = _f(p[i_tq])
            if tq > 0:
                pv += ltp * tq
                pq += tq
            b = int(t // step)
            if bucket is not None and b != bucket and last is not None:
                out.append(last)
            bucket = b
            last = (t, p[i_sym], ltp, _f(p[i_vol]), pv / pq if pq > 0 else 0.0, _f(p[i_bid]), _f(p[i_ask]))
        if last is not None:
            out.append(last)
        streams.append(out)
    return list(heapq.merge(*streams, key=lambda r: r[0]))


def _index_stream(root: Path, day: str) -> list[tuple[float, str, float, float, float, float, float]]:
    """The recorded NIFTY / sector index ticks as samples with the symbol '#L<id>' (last price) or '#P<id>' (previous close), so replay() can feed them to the tracker in time order."""
    out = []
    try:
        with (root / "data" / "ticks" / day / "index_ticks.csv").open(encoding="utf-8", newline="") as h:
            for r in csv.DictReader(h):
                try:
                    out.append((_secs(r["ts"]), f"#{r['kind']}{r['id']}", float(r["value"]), 0.0, 0.0, 0.0, 0.0))
                except (KeyError, ValueError):
                    continue
    except OSError:
        pass
    return out


def replay(root: Path, day: str, samples: list | None = None, compute_every: float = STEP_S, minute_every: float = 60.0) -> dict[str, Any]:
    """Feed the samples through an RSTracker. Returns {'events': [...], 'minutes': {minute_of_day: {symbol: row}}, 'market': {minute: median move}}."""
    import money_flow

    ref = rs_leaders.load_reference(root, day)
    if not ref:
        return {"events": [], "minutes": {}, "market": {}, "error": "no previous-close reference (data/nse_daily/stock_daily.csv)"}
    tr = rs_leaders.RSTracker(ref, money_flow._sector_map(root))
    samples = load_samples(root, day) if samples is None else samples
    events: list[dict[str, Any]] = []
    minutes: dict[int, dict[str, dict[str, Any]]] = {}
    market: dict[int, float] = {}
    next_compute = next_minute = 0.0
    for t, sym, ltp, vol, vwap, bid, ask in samples:
        if sym.startswith("#"):
            tr.set_index(**({"ltp": ltp} if sym[1] == "L" else {"prev": ltp}), sid=int(sym[2:]))
            continue
        h, rem = divmod(t, 3600)
        m, s = divmod(rem, 60)
        tr.update(sym, f"{int(h):02d}:{int(m):02d}:{s:06.3f}", ltp, vol, vwap, bid, ask)
        if t >= next_compute:
            next_compute = t + compute_every
            t0 = time.perf_counter()
            snap = tr.compute(t)
            tr._compute_ms = (time.perf_counter() - t0) * 1000.0
            if snap is None:
                continue
            events.extend(tr.events(snap, t, day))
            if t >= next_minute:
                next_minute = t + minute_every
                mk = int(t // 60)
                market[mk] = snap["market"]["median"]
                lead = {r["s"] for r in snap["_all_leaders"]}
                lag = {r["s"] for r in snap["_all_laggards"]}
                minutes[mk] = {r["s"]: {"rs": round(r["rs"], 2), "rs_sec": r["rs_sec"], "acc2": round(r["acc2"], 2), "leader": r["s"] in lead, "laggard": r["s"] in lag,
                                        "ok": next((x.get("ok") for x in snap["_all_leaders"] + snap["_all_laggards"] if x["s"] == r["s"]), None), "red": snap["market"]["red"]}
                               for r in snap["_rows"]}
    return {"events": events, "minutes": minutes, "market": market}


def series_by_symbol(samples: Iterable) -> dict[str, list[tuple[float, float]]]:
    out: dict[str, list[tuple[float, float]]] = {}
    for t, sym, ltp, *_ in samples:
        if not sym.startswith("#"):
            out.setdefault(sym, []).append((t, ltp))
    return out


def price_at(series: list[tuple[float, float]], t: float) -> float | None:
    """Last price at or before t (None when the stock had no tick by then)."""
    lo, hi, best = 0, len(series) - 1, None
    while lo <= hi:
        mid = (lo + hi) // 2
        if series[mid][0] <= t:
            best, lo = series[mid][1], mid + 1
        else:
            hi = mid - 1
    return best


def market_return(series: Mapping[str, list[tuple[float, float]]], t0: float, t1: float) -> float | None:
    """Median stock's % move between t0 and t1: the market over those minutes."""
    r = []
    for s in series.values():
        a, b = price_at(s, t0), price_at(s, t1)
        if a and b:
            r.append((b / a - 1.0) * 100.0)
    return st.median(r) if len(r) >= 50 else None


def forward_moves(events: list[dict[str, Any]], series: Mapping[str, list[tuple[float, float]]], day: str) -> list[dict[str, Any]]:
    """Add fwd_<h>m (move in the flagged direction) and exc_<h>m (that minus the market's move over the same minutes, same direction) to every event."""
    out = []
    mk_cache: dict[tuple[float, float], float | None] = {}
    for e in events:
        t0 = _secs(str(e["time"]))
        sign = 1.0 if "LEADER" in str(e["kind"]) else -1.0
        s = series.get(str(e["symbol"]))
        row = dict(e, side=sign)
        p0 = price_at(s, t0) if s else None
        for h in HORIZONS_MIN:
            t1 = t0 + h * 60
            row[f"fwd_{h}m"] = row[f"exc_{h}m"] = None
            if not p0 or t1 > MARKET_END_S:
                continue
            p1 = price_at(s, t1)
            key = (t0, t1)
            if key not in mk_cache:
                mk_cache[key] = market_return(series, t0, t1)
            if p1 and mk_cache[key] is not None:
                row[f"fwd_{h}m"] = round(sign * (p1 / p0 - 1.0) * 100.0, 3)
                row[f"exc_{h}m"] = round(sign * ((p1 / p0 - 1.0) * 100.0 - mk_cache[key]), 3)
        out.append(row)
    return out


def _group(rows: list[dict[str, Any]], keyf) -> dict[str, dict[str, Any]]:
    groups: dict[str, list[dict[str, Any]]] = {}
    for r in rows:
        groups.setdefault(str(keyf(r)), []).append(r)
    table = {}
    for k, g in sorted(groups.items()):
        entry: dict[str, Any] = {"n": len(g)}
        for h in HORIZONS_MIN:
            vals = [r[f"exc_{h}m"] for r in g if r.get(f"exc_{h}m") is not None]
            fw = [r[f"fwd_{h}m"] for r in g if r.get(f"fwd_{h}m") is not None]
            entry[f"{h}m"] = {"n": len(vals), "mean_fwd": round(st.mean(fw), 3) if fw else None, "mean_excess": round(st.mean(vals), 3) if vals else None,
                              "beat_market_pct": round(100.0 * sum(1 for v in vals if v > 0) / len(vals), 1) if vals else None}
        table[k] = entry
    return table


def latency_summary(rows: list[dict[str, Any]]) -> dict[str, Any]:
    """lag_s = wall clock minus the newest tick when the flag was written; compute_ms = time to rank all stocks; since_rs1_s = how long the stock had already been 1 % away from the market when
    it was first flagged (only the first flag of a stock and side counts: later re-logs just repeat an old move)."""
    out = {}
    for key in ("lag_s", "compute_ms", "since_rs1_s"):
        vals = sorted(float(r[key]) for r in rows if str(r.get(key, "")) not in ("", "None") and (key != "since_rs1_s" or str(r.get("first", "1")) in ("1", "True")))
        if vals:
            out[key] = {"n": len(vals), "median": round(st.median(vals), 2), "p90": round(vals[int(0.9 * (len(vals) - 1))], 2), "max": round(vals[-1], 2)}
    return out


def ledger_join(root: Path, day: str, minutes: Mapping[int, Mapping[str, Mapping[str, Any]]]) -> dict[str, Any]:
    """What the board said about each paper trade at the minute it was entered, grouped, with how those trades ended."""
    try:
        trades = json.loads((root / "data" / "intraday_movement" / "paper_trade_journal.json").read_text(encoding="utf-8")).get("trades") or []
    except (OSError, ValueError):
        return {"error": "no journal"}
    keys = sorted(minutes)
    rows = []
    for t in trades:
        et = str(t.get("entry_time") or "")
        if not et.startswith(day) or str(t.get("status") or "").upper() == "OPEN":
            continue
        try:
            at = datetime.fromisoformat(et)
            m = at.hour * 60 + at.minute
        except ValueError:
            continue
        mk = max((k for k in keys if k <= m), default=None)
        snap = (minutes.get(mk) or {}).get(str(t.get("symbol"))) if mk is not None else None
        bull = str(t.get("direction") or "").upper() == "BULLISH"
        if not snap:
            state = "no board data"
        elif (snap["leader"] and bull) or (snap["laggard"] and not bull):
            state = "with the board (call on leader / put on laggard)" + (" - checks pass" if snap["ok"] else " - a check failed")
        elif (snap["laggard"] and bull) or (snap["leader"] and not bull):
            state = "against the board (call on laggard / put on leader)"
        else:
            state = "not on the board"
        try:
            ret, pnl = float(t.get("return_percent")), float(t.get("net_pnl"))
        except (TypeError, ValueError):
            continue
        rows.append({"state": state, "ret": ret, "pnl": pnl, "red": bool(snap and snap.get("red"))})
    groups: dict[str, dict[str, Any]] = {}
    for r in rows:
        g = groups.setdefault(r["state"], {"n": 0, "wins": 0, "net_pnl": 0.0, "ret_sum": 0.0})
        g["n"] += 1
        g["wins"] += r["pnl"] > 0
        g["net_pnl"] += r["pnl"]
        g["ret_sum"] += r["ret"]
    return {"n_trades": len(rows), "groups": {k: {"n": g["n"], "win_pct": round(100.0 * g["wins"] / g["n"], 1), "net_pnl": round(g["net_pnl"], 2), "avg_return_pct": round(g["ret_sum"] / g["n"], 2)}
                                              for k, g in sorted(groups.items())}}


def live_events(root: Path, day: str) -> list[dict[str, Any]]:
    try:
        with (root / "data" / "rs_events" / f"{day}.csv").open(encoding="utf-8", newline="") as h:
            return list(csv.DictReader(h))
    except OSError:
        return []


def review(root: Path, day: str, force_replay: bool = False) -> dict[str, Any] | None:
    samples = load_samples(root, day)
    if not samples:
        return None
    rep = replay(root, day, samples)
    live = [] if force_replay else live_events(root, day)
    events, source = (live, "live event log") if live else (rep["events"], "replayed from ticks")
    rows = forward_moves(events, series_by_symbol(samples), day)
    out = {"day": day, "source": source, "n_events": len(rows), "latency": latency_summary(rows),
           "quality_by_kind": _group(rows, lambda r: r["kind"]),
           "quality_by_checks": _group(rows, lambda r: ("checks pass" if str(r.get("checks_ok")) in ("True", "1") else "a check failed" if str(r.get("checks_ok")) in ("False", "0") else "not recorded")),
           "quality_by_failed_check": _group([r for r in rows if r.get("failed")], lambda r: r["failed"]),
           "ledger": ledger_join(root, day, rep["minutes"]), "events": rows}
    folder = root / "data" / "rs_review"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / f"{day}.json").write_text(json.dumps(out, default=str), encoding="utf-8")
    _write_summary(folder)
    return out


def _fmt_quality(table: Mapping[str, Mapping[str, Any]]) -> list[str]:
    lines = ["| group | events | 5m excess | 15m excess | 30m excess | beat market (15m) |", "|---|---|---|---|---|---|"]
    for k, e in table.items():
        cell = lambda h: "-" if e[f"{h}m"]["mean_excess"] is None else f"{e[f'{h}m']['mean_excess']:+.2f}% (n={e[f'{h}m']['n']})"
        b = e["15m"]["beat_market_pct"]
        lines.append(f"| {k} | {e['n']} | {cell(5)} | {cell(15)} | {cell(30)} | {'-' if b is None else str(b) + '%'} |")
    return lines


def _write_summary(folder: Path) -> None:
    parts = ["# Relative-strength board: nightly review (shadow, research only)\n",
             "Excess = the stock's move in the flagged direction (leader = up, laggard = down) minus the median stock's move over the same minutes. Positive = the flag beat the market.\n"]
    for p in sorted(folder.glob("20*.json"), reverse=True):
        try:
            d = json.loads(p.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        parts += [f"\n## {d['day']} - {d['n_events']} events ({d['source']})\n", "**Latency**\n"]
        parts += [f"- {k}: median {v['median']}, p90 {v['p90']}, max {v['max']} (n={v['n']})" for k, v in d.get("latency", {}).items()] or ["- not recorded for this source"]
        parts += ["\n**Decision quality by kind**\n"] + _fmt_quality(d["quality_by_kind"])
        parts += ["\n**By checks**\n"] + _fmt_quality(d["quality_by_checks"])
        if d["quality_by_failed_check"]:
            parts += ["\n**By failed check**\n"] + _fmt_quality(d["quality_by_failed_check"])
        led = d.get("ledger") or {}
        if led.get("groups"):
            parts += [f"\n**Paper trades vs the board at entry ({led['n_trades']} closed)**\n", "| board said | trades | win % | net P&L | avg return % |", "|---|---|---|---|---|"]
            parts += [f"| {k} | {g['n']} | {g['win_pct']} | {g['net_pnl']:,.0f} | {g['avg_return_pct']:+.2f} |" for k, g in led["groups"].items()]
    (folder / "summary.md").write_text("\n".join(parts) + "\n", encoding="utf-8")


def run(day: str, root: Path = ROOT) -> None:
    review(root, day)


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    days = args or [date.today().isoformat()]
    for d in days:
        out = review(ROOT, d, force_replay="--replay" in sys.argv)
        print(d, "no ticks" if out is None else f"{out['n_events']} events ({out['source']}); ledger {out['ledger'].get('n_trades', 0)} trades")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
