    def can_generate(
        self,
        *,
        symbol: str,
        direction: str,
        when: datetime,
    ) -> bool:
        self._ensure_date(when.date())
        key = self._lane_key(symbol, direction)
        if any(
            str(item.get("symbol") or "").upper() == str(symbol).upper()
            and str(item.get("direction") or "").upper() == str(direction).upper()
            and str(item.get("status") or "").upper() == "OPEN"
            for item in self.trades
        ):
            return False
        lane = self.lanes.get(key)
        if not lane:
            return True
        if bool(lane.get("armed", True)):
            return True

        # A generated lane may re-arm only after it has remained genuinely
        # non-actionable for the full configured interval.  Do not use
        # last_seen_at here: that timestamp changes every polling cycle and
        # previously allowed brief signal wobble / polling gaps to create a
        # duplicate trade.
        non_actionable_since = self._parse_time(
            lane.get("non_actionable_since")
        )
        if (
            non_actionable_since is not None
            and not bool(lane.get("last_actionable", True))
            and when - non_actionable_since
            >= timedelta(minutes=self.rearm_minutes)
        ):
            lane = dict(lane)
            lane["armed"] = True
            lane["rearmed_at"] = when.isoformat()
            lane["non_actionable_since"] = None
            self.lanes[key] = lane
            return True

        return False

    def observe_candidate(
        self,
        *,
        symbol: str,
        direction: str,
        stage: str,
        actionable: bool,
        when: datetime,
    ) -> None:
        self._ensure_date(when.date())
        key = self._lane_key(symbol, direction)
        lane = dict(self.lanes.get(key) or {})
        lane.setdefault("armed", True)

        if bool(lane.get("armed", True)):
            # No reset timer is needed while the lane is already eligible.
            lane["non_actionable_since"] = None
        elif actionable:
            # The setup became actionable again before completing the reset
            # interval.  Treat it as the same setup and keep it disarmed.
            lane["non_actionable_since"] = None
        else:
            # Start (or continue) a sustained non-actionable reset interval.
            # A single polling-cycle wobble must never re-arm a traded lane.
            non_actionable_since = self._parse_time(
                lane.get("non_actionable_since")
            )
            if non_actionable_since is None:
                lane["non_actionable_since"] = when.isoformat()
            elif (
                when - non_actionable_since
                >= timedelta(minutes=self.rearm_minutes)
            ):
                lane["armed"] = True
                lane["rearmed_at"] = when.isoformat()
                lane["non_actionable_since"] = None

        lane.update({
            "symbol": str(symbol).upper(),
            "direction": str(direction).upper(),
            "last_stage": str(stage),
            "last_actionable": bool(actionable),
            "last_seen_at": when.isoformat(),
        })
        self.lanes[key] = lane

