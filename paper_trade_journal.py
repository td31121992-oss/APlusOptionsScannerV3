    def __init__(
        self,
        *,
        state_dir: Path,
        report_dir: Path,
        rearm_minutes: int = 180,
    ) -> None:
        self.state_dir = Path(state_dir)
        self.report_dir = Path(report_dir)
        self.state_dir.mkdir(parents=True, exist_ok=True)
        self.report_dir.mkdir(parents=True, exist_ok=True)
